"""Application for LLM evaluation pipeline.

Application Layer - Hexagonal Architecture

Implements the driving port (ForRunningEvaluation) and coordinates:
- Evaluation pipeline execution via driven ports
- Result persistence and finalization

Depends only on port abstractions for testability.
"""

from __future__ import annotations
from datetime import datetime
from typing import Optional

from llm_ensemble.evaluate.application.ports.driving.for_running_evaluation import ForRunningEvaluation
from llm_ensemble.evaluate.application.ports.driven.for_input import ForInput
from llm_ensemble.evaluate.application.ports.driven.for_output import ForOutput
from llm_ensemble.evaluate.application.ports.driven.for_computing_metrics import ForComputingMetrics

from llm_ensemble.evaluate.domain.entities.metric_result import MetricResult
from llm_ensemble.evaluate.domain.evaluate_run_factory import EvaluateRunFactory
from llm_ensemble.libs.runtime.run_info import RunType
from llm_ensemble.libs.logging.structlog_logger import get_logger
from llm_ensemble.libs.logging.log_events import EvaluateLogEvent


class EvaluationApplication(ForRunningEvaluation):
    """Application use case for coordinating evaluation pipeline.

    Implements the driving port ForRunningEvaluation - this IS the application's API.
    Driving adapters (CLI, Web API, etc.) call the run_evaluation() method.
    """

    def __init__(
        self,
        input_port: ForInput,
        output_port: ForOutput,
        metric_adapters: list[ForComputingMetrics],
        run_name: str,
    ):
        """Initialize evaluation use case with port dependencies.

        Args:
            input_port: Port for reading input data
            output_port: Port for writing output report
            metric_adapters: List of metric computation adapters
            run_name: Run identifier (generated by CLI)
        """
        self.input_port = input_port
        self.output_port = output_port
        self.metric_adapters = metric_adapters
        self.run_name = run_name

    def run_evaluation(
        self,
        input_run_name: str,
        official: bool,
        notes: Optional[str],
    ) -> None:
        """Execute the complete evaluation backend.

        This is the main application entry point called by driving adapters (CLI, Web API).

        Backend workflow:
        - Read evaluation data via InputPort
        - For each metric: compute metric via MetricPort
        - Build EvaluateRun entity via factory
        - Write EvaluateRun via OutputPort

        Args:
            input_run_name: Run name to evaluate (infer or aggregate run)
            official: Mark as official run
            notes: Optional notes about this evaluation

        Raises:
            Exception: If any step in the pipeline fails
        """
        logger = get_logger()
        logger.info(EvaluateLogEvent.EVALUATE_STARTED, name=self.run_name)

        start_time = datetime.now()

        # Read evaluation data
        evaluation_data = self.input_port.read(input_run_name)
        logger.info(
            EvaluateLogEvent.INPUT_READ,
            input_run_name=evaluation_data.run_name,
            run_type=evaluation_data.run_type,
        )

        # Compute metrics
        metric_results : list[MetricResult] = []
        for metric_adapter in self.metric_adapters:
            result = metric_adapter.compute(
                evaluation_data.ground_truth,
                evaluation_data.predictions
            )
            metric_results.append(result)
            logger.info(
                EvaluateLogEvent.METRIC_COMPUTED,
                metric=result.name,
                value=result.value
            )

        end_time = datetime.now()

        # Build EvaluateRun entity
        metric_names = [m.name for m in metric_results]
        evaluate_run = EvaluateRunFactory.create(
            io_config_name=self.output_port.io_name,
            input_run_name=evaluation_data.run_name,
            metric_names=metric_names,
            run_name=self.run_name,
            run_type=RunType.OFFICIAL if official else RunType.TEST,
            metric_results=metric_results,
            evaluated_run_type=evaluation_data.run_type,
            evaluated_sample_count=evaluation_data.sample_count,
            start_time=start_time,
            end_time=end_time,
            notes=notes,
        )

        # Write EvaluateRun
        self.output_port.write(evaluate_run)
        logger.info(EvaluateLogEvent.EVALUATE_COMPLETE)

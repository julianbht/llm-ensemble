"""Application for aggregation pipeline.

Application Layer - Hexagonal Architecture

This module contains the complete aggregation backend orchestration.
It handles:
- Infrastructure setup (run directories, logging)
- Aggregation pipeline execution via driven ports
- Result persistence and finalization

This is the backend that the CLI adapter uses.
Depends only on port abstractions for testability.
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional
from uuid import UUID
from collections import defaultdict
from datetime import datetime

from llm_ensemble.infer.domain.entities.infer_run_output import InferRunOutput
from llm_ensemble.infer.domain.entities.llm_judgement import LLMJudgement
from llm_ensemble.aggregate.domain.entities.aggregated_dataset import AggregatedDataset
from llm_ensemble.aggregate.domain.entities.aggregated_vote import AggregatedVote
from llm_ensemble.aggregate.domain.entities.aggregate_run_info import AggregateRunInfo
from llm_ensemble.aggregate.domain.entities.aggregate_run_summary import AggregateRunSummary
from llm_ensemble.aggregate.application.ports.aggregated_judgement_writer import AggregatedJudgementWriter
from llm_ensemble.aggregate.application.ports.aggregation_strategy import AggregationStrategyPort
from llm_ensemble.aggregate.application.ports.judgement_reader import JudgementReader

from llm_ensemble.libs.logging import get_logger
from llm_ensemble.libs.runtime.run_info import RunType
from llm_ensemble.libs.runtime.run_summary_builder import write_standalone_summary
from llm_ensemble.libs.runtime.tag_manager import TagManager


class AggregationApplication:
    """Application use case for coordinating ensemble aggregation pipeline.

    This is the backend application that handles:
    - Logging configuration
    - Aggregation execution (read → group → aggregate → write loop)
    - Result persistence and finalization

    Infrastructure setup (run directories, run naming) is handled by the
    composition root before application instantiation.

    The CLI adapter is a thin wrapper that:
    - Parses CLI arguments
    - Calls this application
    - Presents results (terminal output)

    Depends only on driven port abstractions, enabling unit testing with mocked ports.
    """

    def __init__(
        self,
        judgement_reader: JudgementReader,
        aggregated_judgement_writer: AggregatedJudgementWriter,
        aggregation_strategy_adapter: AggregationStrategyPort,
        run_dir: Path,
        run_name: str,
    ):
        """Initialize aggregation use case with port dependencies.

        Args:
            judgement_reader: Port for reading InferRunOutput records
            aggregated_judgement_writer: Port for writing AggregatedDataset records
            aggregation_strategy_adapter: Port for aggregation strategy (e.g., MajorityVoteAdapter)
            run_dir: Run directory path (created by composition root)
            run_name: Run identifier (generated by CLI)
        """
        self.judgement_reader = judgement_reader
        self.aggregated_judgement_writer = aggregated_judgement_writer
        self.strategy = aggregation_strategy_adapter
        self.run_dir = run_dir
        self.run_name = run_name

    def run_aggregation(
        self,
        aggregation_strategy_name: str,
        io_config_name: str,
        input_run_names: list[str],
        official: bool,
        notes: Optional[str] = None,
        tag: Optional[str] = None,
    ) -> AggregateRunSummary:
        """Execute the complete aggregation backend with infrastructure setup and finalization.

        This is the main application entry point called by the CLI adapter.

        Backend workflow:
        - Setup logging and run metadata
        - Read InferRunOutputs via JudgementReader port
        - Validate sample_fingerprints match
        - Group judgements by dataset_sample_id
        - Apply aggregation strategy to each group
        - Write AggregatedDataset via writer port
        - Write summary and finalize outputs
        - Return summary statistics

        Run directory and run name are provided at construction time by the
        composition root.

        Args:
            aggregation_strategy_name: Name of aggregation strategy (e.g., 'majority_vote')
            io_config_name: Name of the I/O config file
            input_run_names: List of infer run identifiers to read judgements from
            official: Mark as official run
            notes: Notes about this run
            tag: Tag name for easy reference by downstream CLIs

        Returns:
            AggregateRunSummary with statistics, timing, and warnings

        Raises:
            ValueError: If validation fails or strategy not found
            FileNotFoundError: If any run directory doesn't exist
        """
        # Track start time for summary
        start_time = datetime.now()

        # Register tag if provided
        if tag:
            TagManager.register_tag(tag, "aggregate", self.run_name)

        # Create immutable run info
        # NOTE: io_config is not available here - would need to be passed from composition root
        # For now, keeping it minimal with just io_config_name
        run_info = AggregateRunInfo(
            run_name=self.run_name,
            run_type=RunType.OFFICIAL if official else RunType.TEST,
            notes=notes,
            aggregation_strategy_name=aggregation_strategy_name,
            io_config_name=io_config_name,
            io_config=None,  # TODO: Pass from composition root if needed
            input_run_names=input_run_names,
        )

        # Get logger (already configured by composition root)
        logger = get_logger(component="aggregation_application")

        logger.info(
            "starting_aggregation",
            strategy=aggregation_strategy_name,
            io_format=io_config_name,
            input_run_names=input_run_names,
        )
        logger.info("run_directory", path=str(self.run_dir))

        # Read InferRunOutputs (one per run) via reader port
        resolved_run_names = [TagManager.resolve_input(rn, "infer") for rn in input_run_names]
        judged_datasets: list[InferRunOutput] = self.judgement_reader.read(resolved_run_names)

        # Validate completion and sample_fingerprint consistency
        self._validate_judged_datasets(judged_datasets, resolved_run_names)

        # Log validation
        sample_fingerprints = {dataset.sample_fingerprint for dataset in judged_datasets}
        logger.info(
            "validated_judged_datasets",
            num_datasets=len(judged_datasets),
            shared_sample_fingerprint=list(sample_fingerprints)[0][:16] + "..." if sample_fingerprints else "N/A"
        )

        # Group llm_judgements by dataset_sample_id across all runs
        # Key: dataset_sample_id, Value: list of llm_judgements from different runs for that sample
        grouped_by_sample: dict[UUID, list[LLMJudgement]] = defaultdict(list)

        for judged_dataset in judged_datasets:
            for llm_judgement in judged_dataset.llm_judgements:
                # Get dataset_sample_id via llm_prompt → dataset_sample
                dataset_sample_id = llm_judgement.llm_prompt.dataset_sample.id
                grouped_by_sample[dataset_sample_id].append(llm_judgement)

        # Track statistics
        tie_count = 0
        no_valid_votes_count = 0
        aggregated_votes = []

        # Process each dataset_sample_id
        for dataset_sample_id in sorted(grouped_by_sample.keys()):
            # All llm_judgements for this sample (one from each run/model config)
            llm_judgements_for_sample = grouped_by_sample[dataset_sample_id]

            # Apply aggregation strategy to get AggregatedVote
            aggregated_vote: AggregatedVote = self.strategy.aggregate(llm_judgements_for_sample)

            # Track statistics
            if aggregated_vote.final_label is None:
                no_valid_votes_count += 1
            elif aggregated_vote.final_reasoning and "tie" in aggregated_vote.final_reasoning.lower():
                tie_count += 1

            aggregated_votes.append(aggregated_vote)

            # Log progress
            logger.info(
                "aggregated_sample",
                dataset_sample_id=str(dataset_sample_id)[:8] + "...",
                final_label=aggregated_vote.final_label.label if aggregated_vote.final_label else "None",
                confidence=f"{aggregated_vote.final_confidence:.2f}" if aggregated_vote.final_confidence else "0.00",
                num_llm_judgements=len(llm_judgements_for_sample),
            )

        # Create AggregatedDataset (computes fingerprint and UUID from votes)
        aggregated_dataset = AggregatedDataset.create(aggregated_votes)

        logger.info(
            "created_aggregated_dataset",
            dataset_id=str(aggregated_dataset.id),
            fingerprint=aggregated_dataset.fingerprint[:16] + "...",
            vote_count=aggregated_dataset.vote_count,
        )

        # Write aggregated_dataset via writer port
        write_summary = self.aggregated_judgement_writer.write(
            run_dir=self.run_dir,
            run_info=run_info,
            aggregated_dataset=aggregated_dataset,
        )

        logger.info(
            "write_complete",
            entities_created=write_summary.total_created,
            entities_skipped=write_summary.total_skipped,
        )

        # Build summary
        total_llm_judgements = sum(
            len(judged_dataset.llm_judgements)
            for judged_dataset in judged_datasets
        )

        # Track end time
        end_time = datetime.now()

        # Build warnings summary
        warnings_summary = {}
        if tie_count > 0:
            warnings_summary["tie"] = tie_count
        if no_valid_votes_count > 0:
            warnings_summary["no_valid_votes"] = no_valid_votes_count

        # Construct summary
        summary = AggregateRunSummary(
            start_time=start_time,
            end_time=end_time,
            run_info=run_info,
            input_judgement_count=total_llm_judgements,
            unique_pair_count=len(grouped_by_sample),
            output_aggregated_count=len(aggregated_votes),
            tie_count=tie_count,
            no_valid_votes_count=no_valid_votes_count,
            warnings_summary=warnings_summary if warnings_summary else None,
        )

        # Write standalone summary.json
        write_standalone_summary(summary, self.run_dir)
        logger.info("summary_written", path=str(self.run_dir / "summary.json"))

        logger.info(
            "aggregation_complete",
            input_judgements=summary.input_judgement_count,
            unique_pairs=summary.unique_pair_count,
            output_aggregated=summary.output_aggregated_count,
        )

        # Log warnings summary if any
        if summary.warnings_summary:
            logger.info(
                "warnings_collected",
                **summary.warnings_summary
            )

        return summary

    def _validate_judged_datasets(
        self, judged_datasets: list[InferRunOutput], run_names: list[str]
    ) -> None:
        """Validate that all InferRunOutputs are complete and compatible for aggregation.

        Checks:
        1. All InferRunOutputs have non-NULL sample_fingerprints (run completed successfully)
        2. All sample_fingerprints match (same samples were processed)

        Args:
            judged_datasets: List of InferRunOutput objects loaded by reader
            run_names: Corresponding run names (for error messages)

        Raises:
            ValueError: If validation fails
        """
        if not judged_datasets:
            raise ValueError("No InferRunOutputs found. Cannot aggregate empty list.")

        # Check for NULL sample_fingerprints (incomplete runs)
        for dataset, run_name in zip(judged_datasets, run_names):
            if dataset.sample_fingerprint is None:
                raise ValueError(
                    f"InferRunOutput for run '{run_name}' has NULL sample_fingerprint. "
                    f"This indicates the run did not complete successfully."
                )

        # Check that all sample_fingerprints match
        sample_fingerprints = {dataset.sample_fingerprint for dataset in judged_datasets}
        if len(sample_fingerprints) > 1:
            raise ValueError(
                f"Cannot aggregate runs with different InferRunOutput sample_fingerprints. "
                f"Found {len(sample_fingerprints)} distinct sample_fingerprints. "
                f"This means the runs processed different sets of samples."
            )
